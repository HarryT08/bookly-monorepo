@Injectable()
@CommandHandler(CreateApprovalFlowCommand)
export class CreateApprovalFlowHandler implements ICommandHandler<CreateApprovalFlowCommand> {
  constructor(
    @Inject('ApprovalFlowRepository') private readonly approvalFlowRepository: ApprovalFlowRepository,
    private readonly eventBus: EventBus,
    private readonly loggingService: LoggingService
  ) {}

  async execute(command: CreateApprovalFlowCommand): Promise<ApprovalFlowEntity> {
    this.loggingService.log('Creating approval flow', 'CreateApprovalFlowHandler', LoggingHelper.logParams({ command }));

    const approvalFlow = new ApprovalFlowEntity(
      '', // ID will be generated by repository
      command.name,
      command.createdBy,
      command.description,
      command.programId,
      command.resourceType,
      command.categoryId,
      command.isDefault,
      command.requiresAllApprovals,
      command.autoApprovalEnabled,
      command.reviewTimeHours,
      command.reminderHours,
      true, // isActive,
      new Date(), // createdAt
      new Date() // updatedAt
    );

    const createdFlow = await this.approvalFlowRepository.createApprovalFlow(approvalFlow);
    
    this.loggingService.log('Approval flow created successfully', 'CreateApprovalFlowHandler', LoggingHelper.logParams({ 
      flowId: createdFlow.id 
    }));

    return createdFlow;
  }
}

@Injectable()
@CommandHandler(UpdateApprovalFlowCommand)
export class UpdateApprovalFlowHandler implements ICommandHandler<UpdateApprovalFlowCommand> {
  constructor(
    @Inject('ApprovalFlowRepository') private readonly approvalFlowRepository: ApprovalFlowRepository,
    private readonly loggingService: LoggingService
  ) {}

  async execute(command: UpdateApprovalFlowCommand): Promise<ApprovalFlowEntity> {
    this.loggingService.log('Updating approval flow', 'UpdateApprovalFlowHandler', LoggingHelper.logParams({ command }));

    const existingFlow = await this.approvalFlowRepository.findApprovalFlowById(command.id);
    if (!existingFlow) {
      throw new Error(`Approval flow with ID ${command.id} not found`);
    }

    const updatedFlow = await this.approvalFlowRepository.updateApprovalFlow(command.id, {
      name: command.name,
      description: command.description,
      requiresAllApprovals: command.requiresAllApprovals,
      autoApprovalEnabled: command.autoApprovalEnabled,
      reviewTimeHours: command.reviewTimeHours,
      reminderHours: command.reminderHours,
      isActive: command.isActive
    });

    this.loggingService.log('Approval flow updated successfully', 'UpdateApprovalFlowHandler', LoggingHelper.logParams({ 
      flowId: updatedFlow.id 
    }));

    return updatedFlow;
  }
}

