@Injectable()
@CommandHandler(SubmitReservationForApprovalCommand)
export class SubmitReservationForApprovalHandler implements ICommandHandler<SubmitReservationForApprovalCommand> {
  constructor(
    @Inject('ApprovalFlowRepository') private readonly approvalFlowRepository: ApprovalFlowRepository,
    private readonly eventBus: EventBus,
    private readonly loggingService: LoggingService
  ) {}

  async execute(command: SubmitReservationForApprovalCommand): Promise<void> {
    this.loggingService.log('Submitting reservation for approval', 'SubmitReservationForApprovalHandler', LoggingHelper.logParams({ command }));

    // Find applicable approval flow
    const approvalFlow = await this.approvalFlowRepository.findDefaultApprovalFlow(
      command.programId,
      command.resourceType,
      command.categoryId
    );

    if (!approvalFlow) {
      this.loggingService.log('No approval flow found, auto-approving reservation', 'SubmitReservationForApprovalHandler', LoggingHelper.logParams({ command }));
      // Auto-approve if no flow is configured
      this.eventBus.publish(new ReservationApprovedEvent(
        command.reservationId,
        '', // No request ID for auto-approval
        'SYSTEM',
        '',
        'Auto-approved - no approval flow configured',
        true
      ));
      return;
    }

    // Emit reservation submitted event
    this.eventBus.publish(new ReservationSubmittedEvent(
      command.reservationId,
      command.userId,
      command.resourceId,
      approvalFlow.id
    ));

    // Check if auto-approval is enabled
    if (approvalFlow.canAutoApprove()) {
      this.loggingService.log('Auto-approving reservation', 'SubmitReservationForApprovalHandler', LoggingHelper.logParams({ command }));
      this.eventBus.publish(new ReservationApprovedEvent(
        command.reservationId,
        '',
        'SYSTEM',
        '',
        'Auto-approved by system',
        true
      ));
      return;
    }

    // Create approval requests for each level
    const levels = await this.approvalFlowRepository.findApprovalLevelsByFlowId(approvalFlow.id);
    const firstLevel = levels.find(level => level.level === 1);

    if (firstLevel) {
      const timeoutAt = firstLevel.timeoutHours 
        ? new Date(Date.now() + firstLevel.timeoutHours * 60 * 60 * 1000)
        : undefined;

      const approvalRequest = new ApprovalRequestEntity(
        '', // ID will be generated by repository
        command.reservationId,
        firstLevel.id,
        ApprovalRequestStatus.PENDING,
        undefined,
        undefined,
        new Date(),
        undefined,
        timeoutAt
      );

      const createdRequest = await this.approvalFlowRepository.createApprovalRequest(approvalRequest);

      // Get all approvers for this level
      const approverIds = firstLevel.getAllApprovers();

      this.eventBus.publish(new ApprovalRequestCreatedEvent(
        createdRequest.id,
        command.reservationId,
        firstLevel.id,
        approverIds,
        timeoutAt
      ));
    }

    this.loggingService.log('Reservation submitted for approval successfully', 'SubmitReservationForApprovalHandler', LoggingHelper.logParams({ command }));
  }
}

@Injectable()
@CommandHandler(ProcessApprovalRequestCommand)
export class ProcessApprovalRequestHandler implements ICommandHandler<ProcessApprovalRequestCommand> {
  constructor(
    @Inject('ApprovalFlowRepository') private readonly approvalFlowRepository: ApprovalFlowRepository,
    private readonly eventBus: EventBus,
    private readonly loggingService: LoggingService
  ) {}

  async execute(command: ProcessApprovalRequestCommand): Promise<void> {
    this.loggingService.log('Processing approval request', 'ProcessApprovalRequestHandler', LoggingHelper.logParams({ command }));

    const request = await this.approvalFlowRepository.findApprovalRequestById(command.requestId);
    if (!request) {
      throw new Error(`Approval request with ID ${command.requestId} not found`);
    }

    if (!request.isPending()) {
      throw new Error(`Approval request ${command.requestId} is not pending`);
    }

    // Create approval action
    const action = new ApprovalActionEntity(
      '', // ID will be generated by repository
      command.requestId,
      command.approverId,
      command.action === 'APPROVE' ? ApprovalActionType.APPROVED : ApprovalActionType.REJECTED,
      command.comments,
      command.ipAddress,
      command.userAgent
    );

    await this.approvalFlowRepository.createApprovalAction(action);

    // Update approval request
    const updatedRequest = command.action === 'APPROVE' 
      ? request.approve(command.approverId, command.comments)
      : request.reject(command.approverId, command.comments);

    await this.approvalFlowRepository.updateApprovalRequest(command.requestId, updatedRequest);

    // Get the approval level and flow
    const level = await this.approvalFlowRepository.findApprovalLevelById(request.levelId);
    if (!level) {
      throw new Error(`Approval level ${request.levelId} not found`);
    }

    const flow = await this.approvalFlowRepository.findApprovalFlowById(level.flowId);
    if (!flow) {
      throw new Error(`Approval flow ${level.flowId} not found`);
    }

    if (command.action === 'APPROVE') {
      // Check if this completes the approval process
      const isComplete = flow.isComplete(level.level);
      
      this.eventBus.publish(new ReservationApprovedEvent(
        request.reservationId,
        command.requestId,
        command.approverId,
        request.levelId,
        command.comments,
        isComplete
      ));

      // If not complete, create next level request
      if (!isComplete) {
        const nextLevel = flow.getNextLevel(level.level);
        if (nextLevel) {
          const timeoutAt = nextLevel.timeoutHours 
            ? new Date(Date.now() + nextLevel.timeoutHours * 60 * 60 * 1000)
            : undefined;

          const nextRequest = new ApprovalRequestEntity(
            '',
            request.reservationId,
            nextLevel.id,
            ApprovalRequestStatus.PENDING,
            undefined,
            undefined,
            new Date(),
            undefined,
            timeoutAt
          );

          const createdNextRequest = await this.approvalFlowRepository.createApprovalRequest(nextRequest);

          this.eventBus.publish(new ApprovalRequestCreatedEvent(
            createdNextRequest.id,
            request.reservationId,
            nextLevel.id,
            nextLevel.getAllApprovers(),
            timeoutAt
          ));
        }
      }
    } else {
      this.eventBus.publish(new ReservationRejectedEvent(
        request.reservationId,
        command.requestId,
        command.approverId,
        request.levelId,
        command.comments
      ));
    }

    this.loggingService.log('Approval request processed successfully', 'ProcessApprovalRequestHandler');
  }
}

