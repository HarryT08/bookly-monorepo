@Injectable()
@CommandHandler(ProcessTimeoutCommand)
export class ProcessTimeoutHandler implements ICommandHandler<ProcessTimeoutCommand> {
  constructor(
    @Inject('ApprovalFlowRepository') private readonly approvalFlowRepository: ApprovalFlowRepository,
    private readonly eventBus: EventBus,
    private readonly loggingService: LoggingService
  ) {}

  async execute(command: ProcessTimeoutCommand): Promise<void> {
    this.loggingService.log('Processing timeout', 'ProcessTimeoutHandler', LoggingHelper.logParams({ command }));

    const request = await this.approvalFlowRepository.findApprovalRequestById(command.requestId);
    if (!request) {
      throw new Error(`Approval request with ID ${command.requestId} not found`);
    }

    if (!request.isPending() || !request.isExpired()) {
      return; // Nothing to do
    }

    const timeoutRequest = request.timeout();
    await this.approvalFlowRepository.updateApprovalRequest(command.requestId, timeoutRequest);

    this.eventBus.publish(new ApprovalRequestTimeoutEvent(
      command.requestId,
      request.reservationId,
      request.levelId
    ));

    this.loggingService.log('Timeout processed successfully', 'ProcessTimeoutHandler');
  }
}

@Injectable()
@CommandHandler(SendApprovalReminderCommand)
export class SendApprovalReminderHandler implements ICommandHandler<SendApprovalReminderCommand> {
  constructor(
    @Inject('ApprovalFlowRepository') private readonly approvalFlowRepository: ApprovalFlowRepository,
    private readonly eventBus: EventBus,
    private readonly loggingService: LoggingService
  ) {}

  async execute(command: SendApprovalReminderCommand): Promise<void> {
    this.loggingService.log('Sending approval reminder', 'SendApprovalReminderHandler', LoggingHelper.logParams({ command }));

    const request = await this.approvalFlowRepository.findApprovalRequestById(command.requestId);
    if (!request || !request.isPending()) {
      return; // Nothing to do
    }

    const level = await this.approvalFlowRepository.findApprovalLevelById(request.levelId);
    if (!level) {
      return;
    }

    const approverIds = level.getAllApprovers();

    this.eventBus.publish(new ApprovalReminderEvent(
      command.requestId,
      request.reservationId,
      approverIds,
      command.reminderType
    ));

    this.loggingService.log('Approval reminder sent successfully', 'SendApprovalReminderHandler');
  }
}
